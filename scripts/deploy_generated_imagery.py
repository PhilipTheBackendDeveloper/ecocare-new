def process_figure4(cutout):
    """
    Slot 3 & 7: figure4.png (279x273) - Cutout of cleaner on CTA banner
    """
    dest_path = get_dest("img/figure/figure4.png")
    target_w, target_h = 279, 273
    canvas = Image.new("RGBA", (target_w, target_h), (0, 0, 0, 0))

    # Scale cutout to fill height
    scale = target_h / cutout.height
    new_w = int(cutout.width * scale)
    new_h = target_h
    scaled = cutout.resize((new_w, new_h), Image.Resampling.LANCZOS)

    paste_x = (target_w - new_w) // 2
    canvas.paste(scaled, (paste_x, 0), scaled)
    canvas.save(dest_path, "PNG", optimize=True)
    print(f"✓ Updated {dest_path} (279x273)")


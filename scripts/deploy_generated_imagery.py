def extract_cutout(src_path, feather_radius=1.5):
    """
    Extracts the subject from a white/light studio background with smooth alpha feathering.
    """
    im = Image.open(src_path).convert("RGB")
    w, h = im.size
    pix = im.load()

    visited = bytearray(w * h)
    q = deque()

    # Seed flood fill from image perimeter
    for x in range(w):
        q.append((x, 0))
        q.append((x, h - 1))
        visited[0 * w + x] = 1
        visited[(h - 1) * w + x] = 1

    for y in range(h):
        q.append((0, y))
        q.append((w - 1, y))
        visited[y * w + 0] = 1
        visited[y * w + (w - 1)] = 1

    def is_bg(r, g, b):
        # Off-white / light studio background detection
        return r > 215 and g > 215 and b > 215 and abs(r - g) < 25 and abs(g - b) < 25 and abs(r - b) < 25

    while q:
        cx, cy = q.popleft()
        for dx, dy in ((-1,0), (1,0), (0,-1), (0,1)):
            nx, ny = cx + dx, cy + dy
            if 0 <= nx < w and 0 <= ny < h:
                idx = ny * w + nx
                if not visited[idx]:
                    r, g, b = pix[nx, ny]
                    if is_bg(r, g, b):
                        visited[idx] = 1
                        q.append((nx, ny))

    mask = Image.new("L", (w, h), 255)
    mask_pix = mask.load()
    for y in range(h):
        for x in range(w):
            if visited[y * w + x]:
                mask_pix[x, y] = 0

    mask_feather = mask.filter(ImageFilter.GaussianBlur(feather_radius))
    rgba = im.convert("RGBA")
    rgba.putalpha(mask_feather)

    # Crop to subject bounding box
    bbox = rgba.getbbox()
    if bbox:
        # Give a small padding
        return rgba.crop(bbox)
    return rgba

def process_figure5():
    """
    Slot 2: figure5.png (652x652) - Tilted polaroid frames on homepage
    """
    dest_path = get_dest("img/figure/figure5.png")
    fig5 = Image.open(dest_path).convert("RGBA")
    w, h = fig5.size
    pix = fig5.load()

    mask_top = Image.new("L", (w, h), 0)
    mask_bottom = Image.new("L", (w, h), 0)
    top_pix = mask_top.load()
    bottom_pix = mask_bottom.load()

    for y in range(120, 390):
        for x in range(120, 440):
            r, g, b, a = pix[x, y]
            if a > 240 and not (r > 240 and g > 240 and b > 240):
                top_pix[x, y] = 255

    for y in range(300, 620):
        for x in range(250, 580):
            r, g, b, a = pix[x, y]
            if a > 240 and not (r > 240 and g > 240 and b > 240):
                bottom_pix[x, y] = 255

    mask_top_smooth = mask_top.filter(ImageFilter.GaussianBlur(1.2))
    mask_bottom_smooth = mask_bottom.filter(ImageFilter.GaussianBlur(1.2))

    # Top photo: Residential cleaning crew in green polos
    top_src = Image.open(SRC_RESIDENTIAL_CLEANING).convert("RGBA")
    top_crop = ImageOps.fit(top_src, (340, 290), Image.Resampling.LANCZOS)
    top_rot = top_crop.rotate(-18, expand=True, resample=Image.Resampling.BICUBIC)

    canvas_top = Image.new("RGBA", (w, h), (0, 0, 0, 0))
    cx = 275 - top_rot.width // 2
    cy = 250 - top_rot.height // 2
    canvas_top.paste(top_rot, (cx, cy), top_rot)

    # Bottom photo: Carpet extraction action
    bottom_src = Image.open(SRC_CARPET_ACTION).convert("RGBA")
    bottom_crop = ImageOps.fit(bottom_src, (340, 310), Image.Resampling.LANCZOS)
    bottom_rot = bottom_crop.rotate(15, expand=True, resample=Image.Resampling.BICUBIC)

    canvas_bottom = Image.new("RGBA", (w, h), (0, 0, 0, 0))
    bx = 410 - bottom_rot.width // 2
    by = 460 - bottom_rot.height // 2
    canvas_bottom.paste(bottom_rot, (bx, by), bottom_rot)

    # Composite
    result = fig5.copy()
    result.paste(canvas_top, (0, 0), mask_top_smooth)
    result.paste(canvas_bottom, (0, 0), mask_bottom_smooth)
    result.save(dest_path, "PNG", optimize=True)
    print(f"✓ Updated {dest_path} (652x652)")

